# --------------------------------------------------------------------- 主流程
def main() -> None:
    doc = Document(str(SRC))

    # 保留封面与赛题清单，删除其后全部内容
    paragraphs = list(doc.paragraphs)
    for paragraph in paragraphs[KEEP_PARAGRAPHS:]:
        paragraph._element.getparent().remove(paragraph._element)

    styles_element = doc.styles.element
    _define_style(styles_element, "Heading1", "heading 1", outline=0, east_asia=HEI,
                  size_half=32, bold=True, color=INK, before=400, after=200,
                  line=360, keep_next=True)
    _define_style(styles_element, "Heading2", "heading 2", outline=1, east_asia=HEI,
                  size_half=28, bold=True, color=INK, before=300, after=160,
                  line=340, keep_next=True)
    _define_style(styles_element, "Heading3", "heading 3", outline=2, east_asia=HEI,
                  size_half=24, bold=True, color=INK, before=240, after=120,
                  line=320, keep_next=True)
    _define_style(styles_element, "Caption", "caption", east_asia=SONG, size_half=18,
                  color=GREY, before=60, after=60, align="center")
    _define_style(styles_element, "ReportBody", "报告正文", east_asia=SONG, size_half=24,
                  before=0, after=120, line=360, first_line_chars="200", align="both")

    section = doc.sections[0]
    footer = section.footer
    footer.is_linked_to_previous = False
    footer_paragraph = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    for existing in list(footer_paragraph.runs):
        existing._element.getparent().remove(existing._element)
    footer_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _field(footer_paragraph, " PAGE ", "1")

    build(Report(doc))

    # 目标文件可能正被 WPS/Word 打开（存在 ~$ 锁文件），此时写入会被拒绝。
    # 允许通过命令行参数指定替代输出路径，避免为此杀掉用户正在编辑的进程。
    target = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DST
    try:
        doc.save(str(target))
    except PermissionError:
        raise SystemExit(
            f"无法写入 {target}：文件正被 WPS/Word 打开。"
            "请关闭该文档后重试，或传入另一个输出路径。"
        )
    print("written:", target)


if __name__ == "__main__":
    main()
