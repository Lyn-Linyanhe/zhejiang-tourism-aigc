# --------------------------------------------------------------------- XML 工具
def _sub(parent, tag, **attrs):
    element = OxmlElement(tag)
    for key, value in attrs.items():
        element.set(qn(key), str(value))
    parent.append(element)
    return element


def _find_style(styles_element, style_id):
    for style in styles_element.findall(qn("w:style")):
        if style.get(qn("w:styleId")) == style_id:
            return style
    return None


def _define_style(styles_element, style_id, name, *, based="Normal", outline=None,
                  east_asia=SONG, latin=LATIN, size_half=24, bold=False, color=None,
                  before=0, after=0, line=None, first_line_chars=None, align=None,
                  keep_next=False):
    """新建或覆盖一个段落样式。同名样式只保留一份。"""
    style = _find_style(styles_element, style_id)
    if style is not None:
        styles_element.remove(style)

    style = _sub(styles_element, "w:style", **{"w:type": "paragraph", "w:styleId": style_id})
    _sub(style, "w:name", **{"w:val": name})
    if based:
        _sub(style, "w:basedOn", **{"w:val": based})
    _sub(style, "w:next", **{"w:val": "Normal"})
    _sub(style, "w:qFormat")

    ppr = _sub(style, "w:pPr")
    if keep_next:
        _sub(ppr, "w:keepNext")
    if outline is not None:
        _sub(ppr, "w:outlineLvl", **{"w:val": outline})
    if before or after or line is not None:
        spacing = _sub(ppr, "w:spacing")
        if before:
            spacing.set(qn("w:before"), str(before))
        if after:
            spacing.set(qn("w:after"), str(after))
        if line is not None:
            spacing.set(qn("w:line"), str(line))
            spacing.set(qn("w:lineRule"), "auto")
    if first_line_chars is not None:
        size_pt = size_half / 2
        first_line_twips = int(size_pt * int(first_line_chars) / 100 * 20)
        _sub(ppr, "w:ind", **{"w:firstLineChars": str(first_line_chars),
                              "w:firstLine": str(first_line_twips)})
    if align:
        _sub(ppr, "w:jc", **{"w:val": align})

    rpr = _sub(style, "w:rPr")
    _sub(rpr, "w:rFonts", **{"w:ascii": latin, "w:hAnsi": latin,
                             "w:eastAsia": east_asia, "w:cs": latin, "w:hint": "eastAsia"})
    if bold:
        _sub(rpr, "w:b")
        _sub(rpr, "w:bCs")
    if color is not None:
        _sub(rpr, "w:color", **{"w:val": str(color)})
    _sub(rpr, "w:sz", **{"w:val": str(size_half)})
    _sub(rpr, "w:szCs", **{"w:val": str(size_half)})
    return style


def _field(paragraph, instruction, placeholder=""):
    run = paragraph.add_run()
    _sub(run._r, "w:fldChar", **{"w:fldCharType": "begin"})
    instr = _sub(run._r, "w:instrText", **{"xml:space": "preserve"})
    instr.text = instruction
    _sub(run._r, "w:fldChar", **{"w:fldCharType": "separate"})
    if placeholder:
        text = _sub(run._r, "w:t")
        text.text = placeholder
    _sub(run._r, "w:fldChar", **{"w:fldCharType": "end"})
    return run


def _three_line(table):
    """三线表：顶线、表头下线、底线；不要竖线与内部横线。"""
    tbl_pr = table._tbl.tblPr
    borders = _sub(tbl_pr, "w:tblBorders")
    for edge, size in (("top", 12), ("bottom", 12), ("left", 0), ("right", 0),
                       ("insideH", 0), ("insideV", 0)):
        node = _sub(borders, f"w:{edge}")
        node.set(qn("w:val"), "single" if size else "none")
        node.set(qn("w:sz"), str(size))
        node.set(qn("w:space"), "0")
        node.set(qn("w:color"), "1F3B63" if size else "auto")
    for cell in table.rows[0].cells:
        tc_pr = cell._tc.get_or_add_tcPr()
        cell_borders = _sub(tc_pr, "w:tcBorders")
        bottom = _sub(cell_borders, "w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "6")
        bottom.set(qn("w:space"), "0")
        bottom.set(qn("w:color"), "1F3B63")


# --------------------------------------------------------------------- 构建器
class Report:
    def __init__(self, doc):
        self.doc = doc
        self.body_style = doc.styles["报告正文"]
        self.caption_style = doc.styles["Caption"]

    # --- 标题 ---
    def h1(self, text):
        paragraph = self.doc.add_paragraph(text, style="Heading 1")
        paragraph.paragraph_format.space_before = Pt(18)
        paragraph.paragraph_format.space_after = Pt(10)
        return paragraph

    def h2(self, text):
        paragraph = self.doc.add_paragraph(text, style="Heading 2")
        paragraph.paragraph_format.space_before = Pt(12)
        paragraph.paragraph_format.space_after = Pt(6)
        return paragraph

    def h3(self, text):
        paragraph = self.doc.add_paragraph(text, style="Heading 3")
        paragraph.paragraph_format.space_before = Pt(10)
        paragraph.paragraph_format.space_after = Pt(4)
        return paragraph

    # --- 正文 ---
    def p(self, *paragraphs):
        result = None
        for text in paragraphs:
            result = self.doc.add_paragraph(text, style="报告正文")
        return result

    def ps(self, *paragraphs):
        return self.p(*paragraphs)

    def bullets(self, items, start=1, marker="（{}）"):
        for offset, item in enumerate(items):
            paragraph = self.doc.add_paragraph(style="报告正文")
            paragraph.paragraph_format.first_line_indent = Cm(0)
            paragraph.paragraph_format.left_indent = Cm(0.74)
            paragraph.paragraph_format.space_after = Pt(2)
            paragraph.add_run(marker.format(start + offset) + item)

    def note(self, text):
        paragraph = self.doc.add_paragraph(style="Caption")
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = paragraph.add_run(text)
        run.font.size = Pt(9)
        run.font.color.rgb = GREY
        return paragraph

    # --- 图表 ---
    def figure(self, filename, caption, width_cm=TEXT_WIDTH_CM):
        self.doc.add_picture(str(ASSETS / filename), width=Cm(width_cm))
        self.doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.doc.paragraphs[-1].paragraph_format.space_after = Pt(4)
        self.caption(caption)

    def caption(self, text):
        paragraph = self.doc.add_paragraph(text, style="Caption")
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
        paragraph.paragraph_format.space_after = Pt(10)
        return paragraph

    def table(self, caption, headers, rows, widths=None, size=9):
        self.caption(caption)
        table = self.doc.add_table(rows=1, cols=len(headers))
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False
        if widths is None:
            widths = [1.0 / len(headers)] * len(headers)

        for index, text in enumerate(headers):
            cell = table.rows[0].cells[index]
            cell.text = ""
            paragraph = cell.paragraphs[0]
            paragraph.paragraph_format.space_before = Pt(2)
            paragraph.paragraph_format.space_after = Pt(2)
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = paragraph.add_run(text)
            run.bold = True
            run.font.size = Pt(size)
            run.font.name = LATIN
            run._element.rPr.rFonts.set(qn("w:eastAsia"), SONG)

        for row_data in rows:
            cells = table.add_row().cells
            for index, text in enumerate(row_data):
                cells[index].text = ""
                paragraph = cells[index].paragraphs[0]
                paragraph.paragraph_format.space_before = Pt(2)
                paragraph.paragraph_format.space_after = Pt(2)
                run = paragraph.add_run(text)
                run.font.size = Pt(size)
                run.font.name = LATIN
                run._element.rPr.rFonts.set(qn("w:eastAsia"), SONG)

        for row in table.rows:
            for index, cell in enumerate(row.cells):
                cell.width = Cm(TEXT_WIDTH_CM * widths[index])

        _three_line(table)
        self.doc.add_paragraph(style="报告正文").paragraph_format.space_after = Pt(0)
        return table


